// Fetch real cover art for the Kori catalog and store it locally in assets/posters/.
// Runs on GitHub Actions (which has outbound internet) because local sandboxes may not.
// Output: posters.js mapping catalog id -> local image path.
const fs = require('fs');
const path = require('path');

const html = fs.readFileSync(path.join(__dirname, '..', 'index.html'), 'utf8');
const match = html.match(/const RAW\s*=\s*(\[[\s\S]*?\n\]);/);
if (!match) throw new Error('Could not locate RAW catalog in index.html');
const RAW = Function('return ' + match[1])();

const OUT_DIR = path.join(__dirname, '..', 'assets', 'posters');
fs.mkdirSync(OUT_DIR, { recursive: true });
const HEADERS = { 'User-Agent': 'Mozilla/5.0 (compatible; KoriCatalogBot/1.0)', 'Accept': 'application/json,image/*' };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function get(url, binary = false) {
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch(url, { headers: HEADERS, redirect: 'follow' });
      if (res.status === 429) { await sleep(1500 * (attempt + 1)); continue; }
      if (!res.ok) throw new Error('HTTP ' + res.status);
      return binary ? Buffer.from(await res.arrayBuffer()) : await res.json();
    } catch (e) {
      if (attempt === 2) throw e;
      await sleep(600);
    }
  }
}

(async () => {
  const mapping = {};
  let ok = 0, failed = 0;
  for (let i = 0; i < RAW.length; i++) {
    const title = RAW[i][0];
    const id = i + 1;
    try {
      const data = await get('https://api.jikan.moe/v4/anime?q=' + encodeURIComponent(title) + '&limit=1&sfw=true');
      const a = data.data && data.data[0];
      if (!a) throw new Error('no Jikan match');
      const url = (a.images && a.images.jpg && (a.images.jpg.large_image_url || a.images.jpg.image_url));
      if (!url) throw new Error('no image url');
      const buf = await get(url, true);
      if (buf.length < 2000) throw new Error('image too small: ' + buf.length);
      const file = id + '.jpg';
      fs.writeFileSync(path.join(OUT_DIR, file), buf);
      mapping[id] = 'assets/posters/' + file;
      ok++;
      console.log('OK   ' + id + '  ' + title + '  (' + buf.length + ' bytes)');
    } catch (e) {
      failed++;
      console.log('SKIP ' + id + '  ' + title + '  ' + String(e.message || e).slice(0, 90));
    }
    await sleep(420); // Jikan allows 3 requests/second.
  }
  fs.writeFileSync(
    path.join(__dirname, '..', 'posters.js'),
    '/* Generated by scripts/fetch-posters.js — id -> local poster image path. */\nconst POSTERS = ' + JSON.stringify(mapping, null, 2) + ';\n'
  );
  console.log('\nDone. ' + ok + ' covers downloaded, ' + failed + ' using generated fallback.');
})();
